#!/usr/bin/env python3
"""Scan this folder and write pma/library.js, the motion library shown by web/premaid-sim.html.

    python pma/make_index.py

library.js is a plain script ( window.PMA_LIBRARY = [...] ) holding every .pma base64-encoded, so the page can read the library from
http(s) AND from file:// (browsers block fetch() there, but allow <script src>).  Music is NOT embedded: it is referenced by file name
and loaded by the page from this folder:  drop  <same name>.mp3 / .m4a / .aac / .ogg / .opus / .wav / .flac  next to the .pma and re-run.
A same-name .wsdcf (encrypted web-stream container) is only listed as "drm": a browser cannot play it.
"""
import base64, json, os, unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
AUDIO = ('.mp3', '.m4a', '.aac', '.ogg', '.opus', '.wav', '.flac')

def key(name):
    return unicodedata.normalize('NFC', os.path.splitext(name)[0]).casefold()

def main():
    files = sorted(os.listdir(HERE), key=lambda n: unicodedata.normalize('NFC', n).casefold())
    audio, drm = {}, {}
    for fn in files:
        ext = os.path.splitext(fn)[1].lower()
        if ext in AUDIO: audio.setdefault(key(fn), fn)
        elif ext == '.wsdcf': drm.setdefault(key(fn), fn)
    out = []
    for fn in files:
        if not fn.lower().endswith('.pma'): continue
        e = {'title': os.path.splitext(fn)[0], 'pma': fn}
        if key(fn) in audio: e['audio'] = audio[key(fn)]
        elif key(fn) in drm: e['drm'] = drm[key(fn)]
        with open(os.path.join(HERE, fn), 'rb') as f: e['data'] = base64.b64encode(f.read()).decode('ascii')
        out.append(e)
    js = 'window.PMA_LIBRARY=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/') + ';\n'
    with open(os.path.join(HERE, 'library.js'), 'w', encoding='utf-8', newline='\n') as f: f.write('/* generated by pma/make_index.py - do not edit */\n' + js)
    print('pma/library.js: %d motions, %d with audio, %d encrypted-only, %d KB' % (len(out), sum('audio' in e for e in out), sum('drm' in e for e in out), len(js) // 1024))

if __name__ == '__main__': main()
