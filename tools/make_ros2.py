#!/usr/bin/env python3
"""Generate the data-driven files of the ROS 2 packages from the URDF (joint names, limits, groups):
    ros2/premaidai_description/urdf/premaidai.ros2_control.xacro     ros2_control system, 25 position joints (mock / Gazebo / hardware plugin)
    ros2/premaidai_description/config/controllers.yaml               joint_state_broadcaster + joint_trajectory_controller
    ros2/premaidai_moveit_config/config/{premaidai.srdf, joint_limits.yaml, kinematics.yaml, moveit_controllers.yaml, ompl_planning.yaml, initial_positions.yaml}
    python tools/make_ros2.py [--verify]
The hand-written files (package.xml, CMakeLists.txt, launch/*.py, urdf/premaidai.urdf.xacro, rviz) live next to them."""
import importlib.util, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
spec = importlib.util.spec_from_file_location('gen', os.path.join(ROOT, 'mujoco', 'make_premaid_mjcf.py')); gen = importlib.util.module_from_spec(spec); spec.loader.exec_module(gen)
links, joints = gen.parse_urdf(gen.expand_xacro()); rev = [j for j in joints if j.type == 'revolute']
byname = {j.name: j for j in joints}
GROUPS = {'head': 'head_', 'r_arm': 'r_s', 'l_arm': 'l_s', 'r_leg': 'r_hp', 'l_leg': 'l_hp'}

def chain(first):       # joints from the first joint of a limb down to its tip link
    j = byname[first]; out = [j]
    while True:
        nxt = [k for k in joints if k.parent == j.child and k.type == 'revolute']
        if not nxt: return out, j.child
        j = nxt[0]; out.append(j)

CH = {'head': chain('head_ny_joint') if 'head_ny_joint' in byname else None}
CH = {'head': chain('head_ny_joint'), 'r_arm': chain('r_shy_joint'), 'l_arm': chain('l_shy_joint'), 'r_leg': chain('r_hpz_joint'), 'l_leg': chain('l_hpz_joint')}
NAMES = [j.name for g in ('head', 'r_arm', 'l_arm', 'r_leg', 'l_leg') for j in CH[g][0]]
assert sorted(NAMES) == sorted(j.name for j in rev) and len(NAMES) == 25, 'groups must cover the 25 revolute joints exactly once'

def f(x): return '%.9g' % x

def ros2_control():
    o = ['<?xml version="1.0"?>', '<!-- generated by tools/make_ros2.py: do not edit -->',
         '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">',
         '  <xacro:macro name="premaidai_ros2_control" params="use_mock_hardware:=true use_gz:=false serial_port:=/dev/ttyUSB0 controllers_file:=\'\'">',
         '    <ros2_control name="PreMaidSystem" type="system">', '      <hardware>',
         '        <xacro:if value="${use_gz}"><plugin>gz_ros2_control/GazeboSimSystem</plugin></xacro:if>',
         '        <xacro:if value="${use_mock_hardware and not use_gz}">', '          <plugin>mock_components/GenericSystem</plugin>', '          <param name="calculate_dynamics">true</param>', '        </xacro:if>',
         '        <xacro:if value="${not use_mock_hardware and not use_gz}">', '          <!-- real robot: a hardware interface that speaks the PMA protocol (see docs/PROTOCOL.md) is not part of this package yet -->',
         '          <plugin>premaidai_hardware/PreMaidSystem</plugin>', '          <param name="serial_port">${serial_port}</param>', '        </xacro:if>', '      </hardware>']
    for n in NAMES:
        j = byname[n]
        o += ['      <joint name="%s">' % n, '        <command_interface name="position"><param name="min">%s</param><param name="max">%s</param></command_interface>' % (f(j.lo), f(j.hi)),
              '        <state_interface name="position"><param name="initial_value">0.0</param></state_interface>', '        <state_interface name="velocity"/>', '      </joint>']
    o += ['    </ros2_control>', '    <xacro:if value="${use_gz}">', '      <gazebo><plugin filename="gz_ros2_control-system" name="gz_ros2_control::GazeboSimROS2ControlPlugin"><parameters>${controllers_file}</parameters></plugin></gazebo>', '    </xacro:if>',
          '  </xacro:macro>', '</robot>', '']
    return '\n'.join(o)

def controllers():
    j = '\n'.join('      - %s' % n for n in NAMES)
    return '''# generated by tools/make_ros2.py: do not edit
controller_manager:
  ros__parameters:
    update_rate: 100
    joint_state_broadcaster:
      type: joint_state_broadcaster/JointStateBroadcaster
    joint_trajectory_controller:
      type: joint_trajectory_controller/JointTrajectoryController

joint_trajectory_controller:
  ros__parameters:
    joints:
%s
    command_interfaces:
      - position
    state_interfaces:
      - position
      - velocity
    allow_partial_joints_goal: true
    allow_nonzero_velocity_at_trajectory_end: true
    constraints:
      stopped_velocity_tolerance: 0.1
      goal_time: 0.0
''' % j

def srdf():
    o = ['<?xml version="1.0" encoding="UTF-8"?>', '<!-- generated by tools/make_ros2.py (groups = limbs, collision pairs = parent/child links); run the MoveIt Setup Assistant to refine the collision matrix -->', '<robot name="premaidai">']
    for g in ('head', 'r_arm', 'l_arm', 'r_leg', 'l_leg'):
        o.append('  <group name="%s"><chain base_link="base_link" tip_link="%s"/></group>' % (g, CH[g][1]))
    o += ['  <group name="arms"><group name="r_arm"/><group name="l_arm"/></group>', '  <group name="legs"><group name="r_leg"/><group name="l_leg"/></group>',
          '  <group name="whole_body"><group name="head"/><group name="arms"/><group name="legs"/></group>']
    o.append('  <group_state name="home" group="whole_body">'); o += ['    <joint name="%s" value="0"/>' % n for n in NAMES]; o.append('  </group_state>')
    arms_down = {'r_shx_joint': 80, 'l_shx_joint': -80}
    o.append('  <group_state name="arms_down" group="whole_body">'); o += ['    <joint name="%s" value="%s"/>' % (n, f(arms_down.get(n, 0) * 3.141592653589793 / 180)) for n in NAMES]; o.append('  </group_state>')
    o.append('  <virtual_joint name="world_to_base" type="fixed" parent_frame="world" child_link="base_link"/>')
    seen = set()
    for j in joints:
        if (j.parent, j.child) not in seen:
            seen.add((j.parent, j.child)); o.append('  <disable_collisions link1="%s" link2="%s" reason="Adjacent"/>' % (j.parent, j.child))
    o += ['</robot>', '']; return '\n'.join(o)

def joint_limits():
    o = ['# generated by tools/make_ros2.py: do not edit', 'default_velocity_scaling_factor: 0.5', 'default_acceleration_scaling_factor: 0.5', 'joint_limits:']
    for n in NAMES:
        j = byname[n]; o += ['  %s:' % n, '    has_velocity_limits: true', '    max_velocity: %s' % f(j.vel), '    has_acceleration_limits: true', '    max_acceleration: %s' % f(4 * j.vel)]
    return '\n'.join(o) + '\n'

def kinematics():
    o = ['# generated by tools/make_ros2.py: do not edit (5-DoF arms and the 3-DoF head are solved position-only)']
    for g in ('head', 'r_arm', 'l_arm', 'r_leg', 'l_leg'):
        o += ['%s:' % g, '  kinematics_solver: kdl_kinematics_plugin/KDLKinematicsPlugin', '  kinematics_solver_search_resolution: 0.005', '  kinematics_solver_timeout: 0.05', '  position_only_ik: %s' % ('false' if g.endswith('leg') else 'true')]
    return '\n'.join(o) + '\n'

def moveit_controllers():
    return '''# generated by tools/make_ros2.py: do not edit
moveit_controller_manager: moveit_simple_controller_manager/MoveItSimpleControllerManager
moveit_simple_controller_manager:
  controller_names:
    - joint_trajectory_controller
  joint_trajectory_controller:
    type: FollowJointTrajectory
    action_ns: follow_joint_trajectory
    default: true
    joints:
%s
''' % '\n'.join('      - %s' % n for n in NAMES)

def ompl():
    o = ['# generated by tools/make_ros2.py: do not edit', 'planning_plugins:', '  - ompl_interface/OMPLPlanner', 'request_adapters:', '  - default_planning_request_adapters/ResolveConstraintFrames', '  - default_planning_request_adapters/ValidateWorkspaceBounds',
         '  - default_planning_request_adapters/CheckStartStateBounds', '  - default_planning_request_adapters/CheckStartStateCollision', 'response_adapters:', '  - default_planning_response_adapters/AddTimeOptimalParameterization',
         '  - default_planning_response_adapters/ValidateSolution', '  - default_planning_response_adapters/DisplayMotionPath', 'planner_configs:', '  RRTConnectkConfigDefault:', '    type: geometric::RRTConnect', '    range: 0.0']
    for g in ('head', 'r_arm', 'l_arm', 'r_leg', 'l_leg', 'arms', 'legs', 'whole_body'):
        o += ['%s:' % g, '  default_planner_config: RRTConnectkConfigDefault', '  planner_configs:', '    - RRTConnectkConfigDefault']
    return '\n'.join(o) + '\n'

def initial():
    return '# generated by tools/make_ros2.py: do not edit\ninitial_positions:\n' + ''.join('  %s: 0.0\n' % n for n in NAMES)

FILES = {
    'ros2/premaidai_description/urdf/premaidai.ros2_control.xacro': ros2_control(), 'ros2/premaidai_description/config/controllers.yaml': controllers(),
    'ros2/premaidai_moveit_config/config/premaidai.srdf': srdf(), 'ros2/premaidai_moveit_config/config/joint_limits.yaml': joint_limits(), 'ros2/premaidai_moveit_config/config/kinematics.yaml': kinematics(),
    'ros2/premaidai_moveit_config/config/moveit_controllers.yaml': moveit_controllers(), 'ros2/premaidai_moveit_config/config/ompl_planning.yaml': ompl(), 'ros2/premaidai_moveit_config/config/initial_positions.yaml': initial()}

if __name__ == '__main__':
    stale = []
    for rel, text in FILES.items():
        p = os.path.join(ROOT, rel)
        if '--verify' in sys.argv:
            if not os.path.exists(p) or open(p, encoding='utf-8', newline='').read() != text: stale.append(rel)
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True); open(p, 'w', encoding='utf-8', newline='\n').write(text)
    if '--verify' in sys.argv:
        print('STALE: ' + ', '.join(stale) if stale else 'OK: ros2 generated files are up to date'); sys.exit(1 if stale else 0)
    print('wrote', len(FILES), 'files')
